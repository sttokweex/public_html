    $(document).ready(function() {
      // Select the arrow buttons and slides
      const $leftArrow = $('.Slider__leftArrow--1hV');
      const $rightArrow = $('.Slider__rightArrow--l16');
      const $slides = $('.Slider__slide--2nK');

      // Function to update slide classes
      function updateSlides(currentIndex, newIndex) {
        // Remove active classes from current slide
        $slides.eq(currentIndex)
          .removeClass('Slider__fadingActive--2U9')
          .addClass('Slider__visibilityHidden--3pj')
          .attr('aria-hidden', 'true');

        // Add active classes to new slide
        $slides.eq(newIndex)
          .removeClass('Slider__visibilityHidden--3pj')
          .addClass('Slider__fadingActive--2U9')
          .attr('aria-hidden', 'false');
      }

      // Right arrow click (next slide)
      $rightArrow.on('click', function() {
        const $currentSlide = $slides.filter('.Slider__fadingActive--2U9');
        const currentIndex = $slides.index($currentSlide);
        const nextIndex = (currentIndex + 1) % $slides.length; // Loop to first slide if at the end
        updateSlides(currentIndex, nextIndex);
      });

      // Left arrow click (previous slide)
      $leftArrow.on('click', function() {
        const $currentSlide = $slides.filter('.Slider__fadingActive--2U9');
        const currentIndex = $slides.index($currentSlide);
        const prevIndex = (currentIndex - 1 + $slides.length) % $slides.length; // Loop to last slide if at the start
        updateSlides(currentIndex, prevIndex);
      });
    });
  </script>
